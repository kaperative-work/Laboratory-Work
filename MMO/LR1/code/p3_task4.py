class ПартияИзделий:
    ндс = 0.2

    def __init__(self, название, цена, количество):
        if not self.корректная_цена(цена):
            raise ValueError("Цена должна быть положительным числом")
        self.название = название
        self.цена = цена
        self.количество = количество

    def стоимость(self):
        return self.цена * self.количество

    def цена_с_ндс(self):
        return self.цена * (1 + self.ндс)

    @classmethod
    def из_строки(cls, строка):
        название, цена, количество = строка.split(";")
        return cls(название.strip(), float(цена), int(количество))

    @classmethod
    def изменить_ндс(cls, ставка):
        cls.ндс = ставка

    @staticmethod
    def корректная_цена(цена):
        return isinstance(цена, (int, float)) and not isinstance(цена, bool) and цена > 0


партия = ПартияИзделий("Кольцо", 1500, 4)
print("Метод экземпляра, стоимость партии:", партия.стоимость())
print("Цена с НДС:", партия.цена_с_ндс())

из_строки = ПартияИзделий.из_строки("Серьги; 80; 10")
print("Метод класса:", из_строки.название, из_строки.стоимость())

print("Статический метод, цена 0 корректна:", ПартияИзделий.корректная_цена(0))
print("Статический метод, цена 220 корректна:", ПартияИзделий.корректная_цена(220))

ПартияИзделий.изменить_ндс(0.1)
print("После смены ставки НДС цена с налогом:", партия.цена_с_ндс())
