from pathlib import Path


class Животное:
    def __init__(self, порода, стоимость):
        self.порода = порода
        self.стоимость = стоимость

    def способ_передвижения(self):
        return "передвигается"

    def описание(self):
        return f"{self.__class__.__name__}: порода {self.порода}, стоимость {self.стоимость}, {self.способ_передвижения()}"


class Рыбы(Животное):
    def способ_передвижения(self):
        return "плавает"


class Птицы(Животное):
    def способ_передвижения(self):
        return "летает"


class Зоомагазин:
    def __init__(self):
        self.животные = []

    def добавить(self, животное):
        self.животные.append(животное)

    def самая_дорогая(self):
        return max(self.животные, key=lambda animal: animal.стоимость)

    def записать_в_файл(self, путь):
        lines = [animal.описание() for animal in self.животные]
        expensive = self.самая_дорогая()
        lines.append("Самая дорогая порода: " + expensive.описание())
        Path(путь).write_text("\n".join(lines) + "\n", encoding="utf-8")


магазин = Зоомагазин()
магазин.добавить(Рыбы("скалярия", 25))
магазин.добавить(Рыбы("дискус", 80))
магазин.добавить(Птицы("волнистый попугай", 40))
магазин.добавить(Птицы("какаду", 350))

for animal in магазин.животные:
    print(animal.описание())

дорогая = магазин.самая_дорогая()
print("Самая дорогая порода:", дорогая.порода, ", стоимость", дорогая.стоимость)

путь = Path("зоомагазин.txt")
магазин.записать_в_файл(путь)
print("Записано в файл:", путь.resolve())
print(путь.read_text(encoding="utf-8"))
